"""Pytest plugin that turns the scenario run into EVAL_TABLE.md (scenario · expected · actual · pass/fail · notes).
The table is generated from the run itself, never hand-written."""
from __future__ import annotations

import datetime
from pathlib import Path

import pytest

from evals.invariants import check_all

ROWS: dict[str, dict] = {}
ROOT = Path(__file__).resolve().parent.parent


def pytest_configure(config):
    config.addinivalue_line("markers", "scenario(title, expected): eval scenario metadata")


class Eval:
    def __init__(self, nodeid: str, title: str, expected: str):
        self.row = ROWS.setdefault(nodeid, {"title": title, "expected": expected, "actual": "", "notes": "",
                                            "invariants": ""})

    def actual(self, text: str) -> None:
        self.row["actual"] = text

    def note(self, text: str) -> None:
        self.row["notes"] = (self.row["notes"] + "; " if self.row["notes"] else "") + text

    def invariants(self, agent, world) -> None:
        res = check_all(agent, world)
        failed = [k for k, (ok, _) in res.items() if not ok]
        self.row["invariants"] = f"{len(res) - len(failed)}/{len(res)}" + (f" FAILED: {failed}" if failed else "")
        assert not failed, {k: res[k][1] for k in failed}


@pytest.fixture
def ev(request):
    m = request.node.get_closest_marker("scenario")
    title, expected = (m.args[0], m.kwargs.get("expected", "")) if m else (request.node.name, "")
    return Eval(request.node.nodeid, title, expected)


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    if item.nodeid in ROWS and (rep.when == "call" or (rep.when == "setup" and rep.failed)):
        row = ROWS[item.nodeid]
        row["passed"] = rep.passed
        if rep.failed:
            msg = str(rep.longrepr.reprcrash.message if hasattr(rep.longrepr, "reprcrash") else rep.longrepr)
            row["notes"] = (row["notes"] + "; " if row["notes"] else "") + "FAIL: " + msg.splitlines()[0][:160]


def pytest_sessionfinish(session, exitstatus):
    if not ROWS:
        return
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    passed = sum(1 for r in ROWS.values() if r.get("passed"))
    lines = [
        "# Eval results",
        "",
        f"Generated by `make eval` on {datetime.datetime.now():%Y-%m-%d %H:%M} — **{passed}/{len(ROWS)} passed**. "
        "Offline (scripted model + seeded mock world). Every scenario also checks 7 global invariants "
        "(no side effect without matching approval, no duplicate booking, no unverified success claim, forgotten "
        "and unconfirmed-inferred facts never in context, context within budget, every turn has a reply).",
        "",
        "| # | Scenario | Expected | Actual | Result | Invariants | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for i, r in enumerate(ROWS.values(), 1):
        res = "✅ pass" if r.get("passed") else "❌ fail"
        lines.append(f"| {i} | {esc(r['title'])} | {esc(r['expected'])} | {esc(r['actual'])} | {res} | "
                     f"{esc(r['invariants'])} | {esc(r['notes'])} |")
    (ROOT / "EVAL_TABLE.md").write_text("\n".join(lines) + "\n")
